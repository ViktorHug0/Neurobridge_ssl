"""First-draft tables, R1-R4, from the final batteries: ATM-128 (P-main, seeds pooled) and SCORE (original) = SAMGA +
SCORE recovery-aware training, final-epoch checkpoint. Top-1 %, mean over the 10 LOSO subjects (then over seeds).
Writes results/things_eeg/cvpr/final/draft_tables.md.
usage: draft_tables.py
"""
import glob, os

import pandas as pd

F = 'results/things_eeg/cvpr/final'
STACKS = [('ATM-128', 'atm128_s33*'), ('SCORE stack (SAMGA)', 'score_orig_s33*')]
R1 = [('plain', 'Zero-shot (cosine)'), ('csls3', 'CSLS k=3'), ('sattc', 'SATTC'), ('hungarian', 'Hungarian'),
      ('sinkhorn', 'Sinkhorn (OT)'), ('transclip', 'TransCLIP'), ('svtl', 'SVTL'), ('score', 'SCORE deployment'),
      ('sage', 'SAGE')]


def cat(pattern):
    fs = glob.glob(f'{F}/{pattern}')
    return pd.concat([pd.read_csv(f).assign(run=f.split('/')[-2] if 'part_' not in f else f.split('/')[-4]) for f in fs]) if fs else None


def mean(d, by):  # over subjects within a run, then over runs (seeds)
    return d.groupby(['run'] + by).top1.mean().groupby(by).mean()


def r1():
    cols = {}
    for name, runs in STACKS:
        parts = []
        for f in ('r1_competitors.csv', 'sattc.csv', 'r1_transductive.csv'):
            d = cat(f'{runs}/{f}')
            if d is not None:
                parts.append(d[['run', 'subject', 'method', 'top1']])
        if parts:
            d = pd.concat(parts).drop_duplicates(['run', 'subject', 'method'])  # plain appears in two files
            cols[f'{name} (n runs={d.run.nunique()})'] = mean(d, ['method'])
    t = pd.DataFrame(cols).reindex([m for m, _ in R1])
    t.index = [lab for _, lab in R1]
    return t.round(2)


def regimes(regime):
    cols = {}
    for name, runs in STACKS:
        d = cat(f'{runs}/regimes/part_*/regime_rows.csv')
        if d is None:
            continue
        d = d[(d.regime == regime) & d.method.isin(['plain', 'score', 'sage'])]
        m = mean(d, ['law', 'level', 'method']).unstack('method')
        for k in m.columns:
            cols[(name, k)] = m[k]
    return pd.DataFrame(cols).round(1)


def r2():
    rows = {}
    for name, runs in STACKS:
        for kind, method in (('sage', 'full1_3'), ('score', 'score'), ('score', 'plain')):
            d = cat(f'{runs}/stream50_{kind}/part_*/stream_rows.csv')
            if d is None or method not in set(d.method):
                continue
            last = d[d.method == method]
            last = last[last.t == last.groupby(['run', 'subject', 'menu', 'reps', 'seed']).t.transform('max')]
            per_run = lambda x: x.groupby('run').top1.mean().mean()  # noqa: E731
            rows[f'{name}: {method}'] = {'prequential at arrival': per_run(d[d.method == method + '@new']),
                                         'prequential strict-causal': per_run(d[d.method == method + '@prev']),
                                         'end-of-stream buffer': per_run(last)}
    return pd.DataFrame(rows).T.round(1)


def main():
    out = [f'# First-draft tables (generated by CVPR_paper/scripts/draft_tables.py)\n',
           'Top-1 %, mean over 10 LOSO subjects then over seeds. ATM-128: P-main (test-selected checkpoint, calibration '
           'hyper-parameters cross-fold). SCORE stack: SAMGA + SCORE recovery-aware training, final epoch '
           '(SCORE\'s own protocol). "SCORE deployment" on the SCORE stack = SCORE (original); on ATM-128 = SCORE '
           'with our encoder.\n', '## R1 (200 x 200, bijective, 80-repetition queries)\n', r1().to_markdown(), '',
           '## R2 (streaming; 50 refits; pooled over K 25-200, q 5-40, 3 orders)\n', r2().to_markdown(), '',
           '## R3 (partial coverage, 10-repetition queries; level = concepts present U)\n', regimes('R3').to_markdown(), '',
           '## R4 (open gallery, 80-repetition queries; level = distractors D)\n', regimes('R4').to_markdown(), '']
    path = os.path.join(F, 'draft_tables.md')
    open(path, 'w').write('\n'.join(out))
    print('\n'.join(out))


if __name__ == '__main__':
    main()
